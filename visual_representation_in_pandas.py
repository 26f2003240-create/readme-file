url = 'https://data.rbi.org.in/BOE/OpenDocument/2409211840/OpenDocument/opendoc/openDocument.jsp?logonSuccessful=true&shareId=0$0'

# Using a requests session to persist cookies and headers
session = requests.Session()

# Adding standard user-agent headers to mimic a real browser request
headers = {
    'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'
}

try:
    response = session.get(url, headers=headers, timeout=15)
    if response.status_code == 200:
        # Save raw content to inspect if it is HTML or actual CSV data
        with open('rbi_data_raw.csv', 'wb') as f:
            for chunk in response.iter_content(chunk_size=8192):
                f.write(chunk)
        print("Successfully downloaded. Let's try reading the first few lines to verify standard formatting:")
        with open('rbi_data_raw.csv', 'r') as f:
            for _ in range(5):
                print(f.readline())
    else:
        print(f"Failed to download. HTTP Status Code: {response.status_code}")
except Exception as e:
    print(f"An error occurred: {e}")

